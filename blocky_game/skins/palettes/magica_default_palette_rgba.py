def build_default_bytes() -> bytes:
    colors = re.findall(
        r"Color \{ r: (\d+), g: (\d+), b: (\d+), a: (\d+) \}",
        _RUST_SNIPPET,
    )
    if len(colors) != 256:
        raise SystemExit(f"expected 256 colors, got {len(colors)}")
    out = bytearray()
    for r, g, b, a in colors:
        out.extend((int(r), int(g), int(b), int(a)))
    return bytes(out)


